public class e8test {
	public static void main(String[] args) {

		int a = 10;

		Integer xa = a;

		Integer xb = 20;

		int b = xb;

		System.out.println("primitive a = " + a);
		System.out.println("wrapper xa = " + xa);
		System.out.println("wrapper xb = " + xb);
		System.out.println("primitive b (from xb) = " + b);
	}
} 
